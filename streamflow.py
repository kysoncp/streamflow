import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L=6
Ra=170
Rb = 410
P1 = 100
q1 = 120
q2 = 120
x=np.linspace(0, L, 500)
v = np.zeros_like(x)

for i in range (len(x)):
  if x[i] < 2:
    v[i] = Ra - (q1 * x[i])

  elif x[i] < 4:
    v[i] = Ra - (q1 * 2) - P1

  else:
    v[i] = Ra - (q1 * 2) - P1 + Rb - (q2 * (x[i] - 4))

plt.plot(x, v, color='blue')
plt.fill_between(x, v, 0, color='lightblue', alpha=0.7)
plt.xlabel('x (ft)')
plt.ylabel('v (lb)')
plt.title('Shear Diagram')

plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L=6
Ra=170
Rb = 410
P1 = 100
q1 = 120
q2 = 120
x=np.linspace(0, L, 500)
m = np.zeros_like(x)

for i in range (len(x)):
  if x[i] < 2:
    m[i] = (Ra * x[i]) - (q1 * x[i]**2 / 2)

  elif x[i] < 4:
    m[i] = (Ra * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2))

  else:
    m[i] = (Ra * x[i]) \
               - (q1 * 2 * (x[i] - 1)) \
               - (P1 * (x[i] - 2)) \
               + (Rb * (x[i] - 4)) \
               - (q2 * (x[i] - 4) * ((x[i] - 4) / 2))

plt.plot(x, m, color='blue')
plt.fill_between(x, m, 0, color='lightblue', alpha=0.7)
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.title('Moment Diagram')

plt.show()

